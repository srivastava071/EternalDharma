// 🎶 Elements
const audioPlayer = document.getElementById("storyAudio");
const playBtn = document.getElementById("playBtn");
const pauseBtn = document.getElementById("pauseBtn");
const toggleHindiBtn = document.getElementById("toggleHindiBtn");
const hindiText = document.getElementById("hindiText");

let currentStory = "";
let showingHindi = false;

// Open Modal
document.querySelectorAll('.story-card').forEach(card => {
  card.addEventListener('click', () => {
    currentStory = card.dataset.story;

    // Load English by default
    storyText.innerHTML = stories[currentStory];
    audioPlayer.src = storyAudioMap[currentStory];
    audioPlayer.load();

    showingHindi = false;
    toggleHindiBtn.textContent = "Switch to Hindi";

    modal.style.display = "block";
    document.body.style.overflow = "hidden";
  });
});

// Play / Pause
playBtn.onclick = () => audioPlayer.play();
pauseBtn.onclick = () => audioPlayer.pause();

// SWITCH TEXT (English ↔ Hindi)
toggleHindiBtn.onclick = () => {
  if (!showingHindi) {
    storyText.innerHTML = hindiTranslations[currentStory] || "हिंदी अनुवाद उपलब्ध नहीं है।";
    toggleHindiBtn.textContent = "Switch to English";
    showingHindi = true;
  } else {
    storyText.innerHTML = stories[currentStory];
    toggleHindiBtn.textContent = "Switch to Hindi";
    showingHindi = false;
  }
};

// Close modal
closeBtn.addEventListener("click", () => {
  modal.style.display = "none";
  audioPlayer.pause();
  document.body.style.overflow = "auto";
});
